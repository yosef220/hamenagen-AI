'use strict';

/**
 * Copy third-party browser assets from node_modules into the renderer's
 * vendor folder, so the app loads everything locally (offline, CSP-friendly):
 *
 *   - hls.js                 — plays the HLS streams of the radio
 *   - Frank Ruhl Libre       — the display face (luach numerals, titles)
 *   - IBM Plex Sans Hebrew   — the interface face
 *   - Lucide icons           — compiled into one SVG sprite (icons.svg)
 *
 * Runs on `npm install` (postinstall). A missing source is reported and the
 * script exits non-zero only when run with --strict (CI), so a local
 * install never breaks.
 */

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const nm = (...p) => path.join(root, 'node_modules', ...p);
const vendorDir = path.join(root, 'electron', 'renderer', 'vendor');
const strict = process.argv.includes('--strict');
let problems = 0;

function copy(from, to) {
  try {
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(from, to);
    return true;
  } catch (err) {
    problems += 1;
    console.warn(`[vendor] skipped ${path.basename(to)}: ${err.message}`);
    return false;
  }
}

fs.mkdirSync(vendorDir, { recursive: true });

// --- hls.js -----------------------------------------------------------------
copy(nm('hls.js', 'dist', 'hls.min.js'), path.join(vendorDir, 'hls.min.js'));

// --- fonts --------------------------------------------------------------------
// Only the subsets and weights the interface uses (Hebrew + basic Latin).
const FONTS = [
  { family: 'Frank Ruhl Libre', pkg: '@fontsource/frank-ruhl-libre', base: 'frank-ruhl-libre', weights: [400, 500, 700] },
  { family: 'IBM Plex Sans Hebrew', pkg: '@fontsource/ibm-plex-sans-hebrew', base: 'ibm-plex-sans-hebrew', weights: [400, 500, 600] },
];
const SUBSETS = {
  hebrew: 'U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F',
  latin: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
};
const faces = [];
for (const font of FONTS) {
  for (const weight of font.weights) {
    for (const [subset, range] of Object.entries(SUBSETS)) {
      const file = `${font.base}-${subset}-${weight}-normal.woff2`;
      if (copy(nm(font.pkg, 'files', file), path.join(vendorDir, 'fonts', file))) {
        faces.push(
          `@font-face {\n  font-family: '${font.family}';\n  font-style: normal;\n  font-display: swap;\n` +
          `  font-weight: ${weight};\n  src: url('fonts/${file}') format('woff2');\n  unicode-range: ${range};\n}`,
        );
      }
    }
  }
}
fs.writeFileSync(
  path.join(vendorDir, 'fonts.css'),
  `/* Generated by scripts/copy-vendor.js — SIL Open Font License (see fonts/OFL.txt). */\n${faces.join('\n')}\n`,
);
for (const font of FONTS) {
  const lic = nm(font.pkg, 'LICENSE');
  if (fs.existsSync(lic)) copy(lic, path.join(vendorDir, 'fonts', `${font.base}-LICENSE.txt`));
}

// --- icons ----------------------------------------------------------------------
// Each symbol keeps Lucide's 24×24 stroke drawing; CSS sets size and colour.
const ICONS = [
  'house', 'library-big', 'shapes', 'radio', 'download', 'settings', 'search', 'play', 'pause',
  'skip-back', 'skip-forward', 'shuffle', 'repeat', 'repeat-1', 'heart', 'list-music', 'moon', 'sun',
  'monitor', 'volume-2', 'volume-1', 'volume-x', 'x', 'folder-open', 'folder-plus', 'refresh-cw',
  'check', 'chevron-left', 'chevron-right', 'chevron-down', 'cpu', 'triangle-alert', 'loader-circle',
  'external-link', 'trash-2', 'type', 'info', 'history', 'scroll-text', 'timer', 'audio-lines',
  'music-2', 'calendar-days', 'wifi-off', 'circle-play', 'mic-vocal', 'arrow-down-up', 'arrow-down',
  'arrow-up', 'plus', 'list-ordered', 'signal', 'hard-drive-download', 'package', 'circle-check',
  'circle-alert', 'keyboard', 'sliders-horizontal', 'ellipsis', 'list-plus', 'list-start', 'tag', 'ear',
  'book-open', 'check-check', 'undo-2', 'image', 'link', 'clipboard-paste', 'tv', 'list-checks',
  'shield-alert', 'circle-stop',
];
const symbols = [];
for (const name of ICONS) {
  const file = nm('lucide-static', 'icons', `${name}.svg`);
  try {
    const svg = fs.readFileSync(file, 'utf8');
    const inner = svg
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/^[\s\S]*?<svg[^>]*>/, '')
      .replace(/<\/svg>\s*$/, '')
      .replace(/\s+/g, ' ')
      .trim();
    symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`);
  } catch (err) {
    problems += 1;
    console.warn(`[vendor] missing icon ${name}: ${err.message}`);
  }
}
fs.writeFileSync(
  path.join(vendorDir, 'icons.svg'),
  '<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide icons (ISC license), compiled by scripts/copy-vendor.js -->\n' +
  `${symbols.join('\n')}\n</svg>\n`,
);
const lucideLicense = nm('lucide-static', 'LICENSE');
if (fs.existsSync(lucideLicense)) copy(lucideLicense, path.join(vendorDir, 'LUCIDE-LICENSE.txt'));

console.log(`[vendor] hls.js, ${faces.length} font faces, ${symbols.length} icons${problems ? `, ${problems} problem(s)` : ''}`);
if (strict && problems) process.exit(1);
